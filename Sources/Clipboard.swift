/// Pasteboard markers (nspasteboard.org) that ask clipboard managers to stay away: passwords,
/// short-lived data, content an app generated rather than the user copied.
private let skippedTypes: Set<NSPasteboard.PasteboardType> = [
    .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
    .init("org.nspasteboard.AutoGeneratedType"),
]

/// What a clipboard item holds.
enum ClipboardContent: Sendable, Equatable {
    case text(String)
    case image(Data) // PNG
}

/// What to record for the pasteboard's current contents, or nil to skip them. Text wins when a copy
/// has both (a spreadsheet copy also carries a picture of the cells); otherwise an image, as PNG.
func clipboardContent(_ pasteboard: NSPasteboard, app: String?, ignoreApps: [String]) -> ClipboardContent? {
    if let app, ignoreApps.contains(app) { return nil }
    guard !(pasteboard.types ?? []).contains(where: skippedTypes.contains) else { return nil }
    if let text = pasteboard.string(forType: .string) {
        return text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty ? nil : .text(text)
    }
    if let png = pasteboard.data(forType: .png) { return .image(png) }
    if let tiff = pasteboard.data(forType: .tiff),
       let png = NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:]) {
        return .image(png)
    }
    return nil
}

/// An image's size in pixels, read from its header without decoding it.
func imagePixelSize(_ data: Data) -> (width: Int, height: Int)? {
    guard let source = CGImageSourceCreateWithData(data as CFData, nil),
          let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
          let width = properties[kCGImagePropertyPixelWidth] as? Int,
          let height = properties[kCGImagePropertyPixelHeight] as? Int
    else { return nil }
    return (width, height)
}

/// A copy of an image at most `maxPixels` on its longer side, for list rows. ImageIO scales while
/// decoding, so the full-size bitmap is never kept.
func thumbnail(_ data: Data, maxPixels: Int) -> CGImage? {
    guard let source = CGImageSourceCreateWithData(data as CFData, nil) else { return nil }
    let options: [CFString: Any] = [kCGImageSourceCreateThumbnailFromImageAlways: true, kCGImageSourceThumbnailMaxPixelSize: maxPixels]
    return CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary)
}

/// clipboard.sqlite: one row per distinct text or image. Copying one again moves it to the top.
struct ClipboardStore: Sendable {
    static let file = configDir.appending(path: "clipboard.sqlite")
    /// Rows carry at most this many characters of their text: plenty for the preview, and a
    /// huge copy doesn't slow down every keystroke. `content(_:)` has the whole thing.
    static let previewLength = 10_000

    struct Item: Sendable {
        let id: Int64
        let text: String // the first `previewLength` characters; for an image, "Image 2880×1800"
        let length: Int // characters; for an image, bytes
        let imageSize: (width: Int, height: Int)? // nil for text
        let app: String? // bundle id of the app in front when it was copied
        let copiedAt: Date
        var pinned = false // kept first, and never pruned or cleared
    }

    private let db: DatabaseQueue

    /// No path: in memory (tests).
    init(path: String? = nil) throws {
        var config = Configuration()
        // Deleted rows are zeroed on disk instead of lingering in free pages: this is clipboard data.
        config.prepareDatabase { try $0.execute(sql: "PRAGMA secure_delete = ON") }
        db = try path.map { try DatabaseQueue(path: $0, configuration: config) } ?? DatabaseQueue(configuration: config)
        var migrator = DatabaseMigrator()
        migrator.registerMigration("v1") { db in
            try db.execute(sql: """
                CREATE TABLE item (
                    id INTEGER PRIMARY KEY,
                    text TEXT NOT NULL UNIQUE,
                    app TEXT,
                    copiedAt DATETIME NOT NULL);
                CREATE INDEX item_copiedAt ON item(copiedAt);
                """)
        }
        migrator.registerMigration("v2: images") { db in
            // An image row keeps its PNG in `image`, and "image:<SHA-256>" as its text, so UNIQUE(text) dedupes images too.
            try db.execute(sql: """
                ALTER TABLE item ADD COLUMN image BLOB;
                ALTER TABLE item ADD COLUMN width INTEGER;
                ALTER TABLE item ADD COLUMN height INTEGER;
                """)
        }
        migrator.registerMigration("v3: pins") { db in
            try db.execute(sql: "ALTER TABLE item ADD COLUMN pinned INTEGER NOT NULL DEFAULT 0")
        }
        try migrator.migrate(db)
    }

    func record(_ text: String, app: String?, at date: Date = .now) throws {
        try db.write { db in
            try db.execute(sql: """
                INSERT INTO item (text, app, copiedAt) VALUES (?, ?, ?)
                ON CONFLICT (text) DO UPDATE SET app = excluded.app, copiedAt = excluded.copiedAt
                """, arguments: [text, app, date])
        }
    }

    func record(image png: Data, width: Int, height: Int, app: String?, at date: Date = .now) throws {
        let key = "image:" + SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined()
        try db.write { db in
            try db.execute(sql: """
                INSERT INTO item (text, image, width, height, app, copiedAt) VALUES (?, ?, ?, ?, ?, ?)
                ON CONFLICT (text) DO UPDATE SET app = excluded.app, copiedAt = excluded.copiedAt
                """, arguments: [key, png, width, height, app, date])
        }
    }

    /// Newest first. With a query: items containing it (ignoring ASCII case; images match "image"),
    /// then items whose first line fuzzy-matches it well (word starts, like "gco" for "git checkout origin").
    /// Image data stays in the database: `image(_:)` loads one when it's shown.
    func items(matching query: String = "", limit: Int = 200) throws -> [Item] {
        let rows = try db.read { db in
            try Row.fetchAll(db, sql: """
                SELECT id, app, copiedAt, width, height, pinned,
                       CASE WHEN image IS NULL THEN substr(text, 1, ?) ELSE 'Image ' || width || '×' || height END AS head,
                       CASE WHEN image IS NULL THEN length(text) ELSE length(image) END AS length,
                       CASE WHEN image IS NULL THEN instr(lower(text), lower(?)) ELSE instr('image', lower(?)) END > 0 AS hit
                FROM item ORDER BY pinned DESC, copiedAt DESC, id DESC
                """, arguments: [Self.previewLength, query, query])
        }
        let item = { (row: Row) in
            let (width, height) = (row["width"] as Int?, row["height"] as Int?)
            return Item(id: row["id"], text: row["head"], length: row["length"],
                        imageSize: width.flatMap { w in height.map { (w, $0) } }, app: row["app"], copiedAt: row["copiedAt"],
                        pinned: row["pinned"])
        }
        guard !query.isEmpty else { return rows.prefix(limit).map(item) }
        // ponytail: fuzzy runs over every row on each keystroke; fine for ~1000 items, an FTS index if it isn't.
        var hits: [Row] = [], fuzzy: [Row] = []
        for row in rows {
            if row["hit"] as Bool {
                hits.append(row)
            } else if (fuzzyScore(query, String(oneLine(row["head"]).prefix(80))) ?? 0) > 0.5 {
                fuzzy.append(row)
            }
        }
        return (hits + fuzzy).prefix(limit).map(item)
    }

    /// The whole item: all of a long text, or the image.
    func content(_ id: Int64) throws -> ClipboardContent? {
        try db.read { db -> ClipboardContent? in
            guard let row = try Row.fetchOne(db, sql: "SELECT text, image FROM item WHERE id = ?", arguments: [id]) else { return nil }
            if let png = row["image"] as Data? { return .image(png) }
            return .text(row["text"])
        }
    }

    func image(_ id: Int64) throws -> Data? {
        try db.read { try Data.fetchOne($0, sql: "SELECT image FROM item WHERE id = ?", arguments: [id]) }
    }

    func delete(_ id: Int64) throws {
        try db.write { try $0.execute(sql: "DELETE FROM item WHERE id = ?", arguments: [id]) }
    }

    /// Everything but the pinned items.
    func count() throws -> Int { try db.read { try Int.fetchOne($0, sql: "SELECT COUNT(*) FROM item") ?? 0 } }

    func clear() throws {
        try db.write { try $0.execute(sql: "DELETE FROM item WHERE pinned = 0") }
    }

    func pin(_ id: Int64, _ pinned: Bool) throws {
        try db.write { try $0.execute(sql: "UPDATE item SET pinned = ? WHERE id = ?", arguments: [pinned, id]) }
    }

    /// The items copied after `id`'s, in the order they were copied.
    func copied(after id: Int64) throws -> [Int64] {
        try db.read { db in
            try Int64.fetchAll(db, sql: """
                SELECT id FROM item WHERE copiedAt > (SELECT copiedAt FROM item WHERE id = ?) ORDER BY copiedAt, id
                """, arguments: [id])
        }
    }

    func prune(maxItems: Int, maxDays: Int, maxImages: Int = .max, now: Date = .now) throws {
        try db.write { db in
            // Pinned items are kept, and don't count.
            try db.execute(sql: "DELETE FROM item WHERE pinned = 0 AND copiedAt < ?", arguments: [now.addingTimeInterval(-Double(maxDays) * 86_400)])
            try db.execute(sql: """
                DELETE FROM item WHERE pinned = 0 AND id NOT IN (SELECT id FROM item WHERE pinned = 0 ORDER BY copiedAt DESC, id DESC LIMIT ?)
                """, arguments: [maxItems])
            try db.execute(sql: """
                DELETE FROM item WHERE pinned = 0 AND image IS NOT NULL AND id NOT IN
                    (SELECT id FROM item WHERE pinned = 0 AND image IS NOT NULL ORDER BY copiedAt DESC, id DESC LIMIT ?)
                """, arguments: [maxImages])
        }
    }
}

/// Whitespace runs (newlines included) collapsed to single spaces: a list row's preview.
func oneLine(_ text: String) -> String {
    text.prefix(500).split(whereSeparator: \.isWhitespace).joined(separator: " ")
}

/// A clipboard row's age: "now", "5m", "3h", "2d".
func shortAge(_ date: Date, now: Date = .now) -> String {
    let seconds = max(0, now.timeIntervalSince(date))
    return switch seconds {
    case ..<60: String(localized: "now", comment: "An age, short: under a minute")
    case ..<3600: String(localized: "\(Int(seconds / 60))m", comment: "An age, short: 5 minutes")
    case ..<86_400: String(localized: "\(Int(seconds / 3600))h", comment: "An age, short: 3 hours")
    default: String(localized: "\(Int(seconds / 86_400))d", comment: "An age, short: 2 days")
    }
}

/// The clipboard list's section for an item copied at `date`.
func clipboardSection(_ date: Date, now: Date = .now, calendar: Calendar = .current) -> String {
    if calendar.isDate(date, inSameDayAs: now) { return String(localized: "Today", comment: "A day: today") }
    if let yesterday = calendar.date(byAdding: .day, value: -1, to: now), calendar.isDate(date, inSameDayAs: yesterday) {
        return String(localized: "Yesterday", comment: "A day: yesterday")
    }
    return String(localized: "Earlier", comment: "Clipboard history's section: before yesterday")
}

/// Polls the pasteboard and records text and image copies.
@MainActor final class ClipboardHistory {
    let store: ClipboardStore
    /// nil until a config.toml has loaded: a file that's broken at launch must not prune with defaults.
    var settings: Config.Clipboard? { didSet { prune() } }
    private var lastChange = NSPasteboard.general.changeCount // what's on the pasteboard at launch isn't new
    private var timer: Timer?
    /// Clipboard history or links without tracking on (Settings › Features): the pasteboard is looked at twice a second,
    /// every 2 s while you're away. Both off, not at all, and what's copied meanwhile is never seen. A copied link loses
    /// its tracking (`cleanLink`) before it's recorded.
    var recording = false {
        didSet {
            guard recording != oldValue else { return }
            timer?.invalidate()
            timer = nil
            guard recording else { return }
            lastChange = NSPasteboard.general.changeCount
            look()
        }
    }

    /// How long until the next look: twice a second, and every 2 s after a minute with no key or mouse, so the Mac
    /// sleeps more while you're away. Copying takes a key, so nothing copied is missed.
    nonisolated static func pollInterval(idle: TimeInterval) -> TimeInterval { idle > 60 ? 2 : 0.5 }

    private func look() {
        let idle = CGEventSource.secondsSinceLastEventType(.combinedSessionState, eventType: CGEventType(rawValue: ~0)!)
        let interval = Self.pollInterval(idle: idle)
        timer = Timer.scheduledTimer(withTimeInterval: interval, repeats: false) { [weak self] _ in
            MainActor.assumeIsolated {
                guard let self, self.recording else { return }
                self.poll()
                self.look()
            }
        }
        timer?.tolerance = interval / 2 // lets macOS batch the wakeups
    }

    init(store: ClipboardStore) { self.store = store }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        let app = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        let settings = settings ?? .init()
        guard var content = clipboardContent(pasteboard, app: app, ignoreApps: settings.ignoreApps) else { return }
        if Feature.cleanLinks.isOn, case .text(let text) = content, let clean = cleanLink(text) {
            pasteboard.clearContents()
            pasteboard.setString(clean, forType: .string)
            pasteboard.setString(clean, forType: .URL)
            lastChange = pasteboard.changeCount
            content = .text(clean)
        }
        guard Feature.clipboard.isOn else { return } // watching only for links
        do {
            switch content {
            case .text(let text):
                try store.record(text, app: app)
            case .image(let png):
                // ponytail: images over 25 MB aren't kept (a huge TIFF turned PNG); they'd bloat the database.
                guard settings.maxImages > 0, png.count <= 25_000_000, let size = imagePixelSize(png) else { return }
                try store.record(image: png, width: size.width, height: size.height, app: app)
            }
            prune()
        } catch {
            notify(String(localized: "Couldn't save to clipboard history"), error.localizedDescription)
        }
    }

    /// Puts an item back on the pasteboard. Not recorded: the item stays where it is in the list.
    func restore(_ content: ClipboardContent) {
        switch content {
        case .text(let text):
            copyToClipboard(text)
        case .image(let png):
            NSPasteboard.general.clearContents()
            NSPasteboard.general.setData(png, forType: .png) // ponytail: PNG only; add TIFF if some old app can't paste it
        }
        lastChange = NSPasteboard.general.changeCount
    }

    private func prune() {
        guard let settings else { return }
        try? store.prune(maxItems: settings.maxItems, maxDays: settings.maxDays, maxImages: settings.maxImages)
    }
}

/// The clipboard panel's rows.
actor ClipboardProvider: ResultProvider {
    private let store: ClipboardStore
    private let paste: @MainActor @Sendable (ClipboardContent) -> Void
    private let copy: @MainActor @Sendable (ClipboardContent) -> Void
    private let items: @Sendable (String) throws -> [ClipboardStore.Item]
    private var apps: [String: (name: String, path: String)?] = [:] // bundle id → app, looked up once

    init(store: ClipboardStore, paste: @escaping @MainActor @Sendable (ClipboardContent) -> Void,
         copy: @escaping @MainActor @Sendable (ClipboardContent) -> Void,
         items: (@Sendable (String) throws -> [ClipboardStore.Item])? = nil) {
        (self.store, self.paste, self.copy) = (store, paste, copy)
        self.items = items ?? { try store.items(matching: $0) }
    }

    /// What Enter does to an item: paste it, or (from `:copy` / `:delete`) copy or delete it.
    enum Mode: Sendable { case paste, copy, delete }

    /// The clipboard panel's `:` commands.
    nonisolated var verbs: [Verb] {
        [
            Verb(keyword: "copy", title: "Copy Without Pasting", icon: .symbol("doc.on.doc"),
                 targets: { [self] in await rows(for: $0, mode: .copy) }),
            Verb(keyword: "delete", title: "Delete from History", icon: .symbol("trash"),
                 targets: { [self] in await rows(for: $0, mode: .delete) }),
            Verb(keyword: "clear", title: "Clear History", icon: .symbol("trash.fill"),
                 confirm: String(localized: "Delete all clipboard history but the pinned items? This can't be undone."), run: { [store] in
                do { try store.clear() } catch { notify(String(localized: "Couldn't clear clipboard history"), error.localizedDescription) }
            }),
        ]
    }

    func results(for query: String) -> [LauncherResult] { rows(for: query, mode: .paste) }

    func rows(for query: String, mode: Mode) -> [LauncherResult] {
        let items: [ClipboardStore.Item]
        do { items = try self.items(query) } catch { // said, not an empty panel: that looks like nothing was ever copied
            return [LauncherResult(id: "clipboard-unreadable", title: String(localized: "Couldn't read the clipboard history"),
                                   icon: .symbol("exclamationmark.triangle"), score: .infinity, actionTitle: "", action: {},
                                   preview: error.localizedDescription)] // long, with the SQL: a subtitle wouldn't show it
        }
        let store = store
        let now = Date.now
        // The panel never takes focus, so the app in front is the one Enter pastes into. Without
        // Accessibility, Enter can only copy.
        let target = NSWorkspace.shared.frontmostApplication?.localizedName
        let trusted = AXIsProcessTrusted()
        let actionTitle = switch mode {
        case .paste: !trusted ? String(localized: "Copy", comment: "Enter on a clipboard item")
            : target.map { String(localized: "Paste to \($0)") } ?? String(localized: "Paste", comment: "Enter on a clipboard item")
        case .copy: String(localized: "Copy", comment: "Enter on a clipboard item")
        case .delete: String(localized: "Delete", comment: "Enter on a clipboard item: deletes it from the history")
        }
        let pinnedSection = String(localized: "Pinned", comment: "Clipboard history's section: the pinned items")
        return items.enumerated().map { index, item -> LauncherResult in
            let source = item.app.flatMap(app)
            let more = item.length - ClipboardStore.previewLength
            let lines = item.text.count { $0 == "\n" } + 1
            var image: (@MainActor @Sendable () -> NSImage?)? // loaded only when the row is selected
            var details = [(String(localized: "Application"), source?.name ?? item.app ?? String(localized: "Unknown", comment: "An app not known"))]
            var icon: LauncherResult.Icon = source.map { .file($0.path) } ?? .symbol("doc.on.clipboard")
            if let size = item.imageSize {
                image = { (try? store.image(item.id)).flatMap(NSImage.init(data:)) }
                icon = .image("clipboard:\(item.id)") { (try? store.image(item.id)).flatMap { thumbnail($0, maxPixels: 64) } }
                details += [(String(localized: "Dimensions"), "\(size.width) × \(size.height)"),
                            (String(localized: "Size", comment: "Label: a file's size"), item.length.formatted(.byteCount(style: .file)))]
            } else {
                details += [(String(localized: "Characters"), "\(item.length)"), (String(localized: "Lines"), more > 0 ? "\(lines)+" : "\(lines)")]
            }
            let copied = item.copiedAt.formatted(.relative(presentation: .named))
            details.append((String(localized: "Copied", comment: "Label: when a clipboard item was copied"), copied))
            let shown = image != nil ? "" : more > 0 ? item.text + "\n\n" + String(localized: "… \(more) more characters") : item.text
            var actions: (@Sendable () async -> [LauncherResult])?
            if mode == .paste {
                let (id, pinned, picture, itemDetails) = (item.id, item.pinned, image, details)
                actions = { [self] in
                    await actionRows(id, pinned: pinned, pasteTitle: actionTitle, trusted: trusted, preview: shown, image: picture, details: itemDetails)
                }
            }
            return LauncherResult(
                id: "clipboard:\(item.id)",
                title: item.imageSize.map { String(localized: "Image \(String($0.width))×\(String($0.height))") } ?? String(oneLine(item.text).prefix(200)),
                accessory: shortAge(item.copiedAt, now: now),
                icon: icon,
                score: Double(items.count - index), // keep the store's order
                actionTitle: actionTitle,
                action: action(mode, item.id),
                actions: actions,
                staysOpen: mode == .delete,
                section: query.isEmpty ? item.pinned ? pinnedSection : clipboardSection(item.copiedAt, now: now) : nil, // filtered: not in date order
                preview: shown,
                previewImage: image,
                details: details)
        }
    }

    /// Tab on an item: paste it, or only copy it; text that's a link opens, shows in Large Type, or as a QR code beside
    /// the list (Enter copies the picture); a picture opens in Preview or goes to Downloads; and deleting it.
    private func actionRows(_ id: Int64, pinned: Bool, pasteTitle: String, trusted: Bool, preview: String,
                            image: (@MainActor @Sendable () -> NSImage?)?, details: [(String, String)]) -> [LauncherResult] {
        guard let content = try? store.content(id) else { return [] }
        let (paste, copy, store) = (paste, copy, store)
        // What Enter does on each.
        let (copyVerb, pasteVerb) = (String(localized: "Copy", comment: "Enter on a clipboard item's action"),
                                     String(localized: "Paste", comment: "Enter on a clipboard item's action"))
        let (openVerb, showVerb) = (String(localized: "Open", comment: "Enter on a clipboard item's action"),
                                    String(localized: "Show", comment: "Enter on a clipboard item's action: Large Type"))
        let (saveVerb, deleteVerb) = (String(localized: "Save", comment: "Enter on a clipboard item's action"),
                                      String(localized: "Delete", comment: "Enter on a clipboard item's action"))
        var rows: [(title: String, symbol: String, actionTitle: String, picture: CGImage?, action: @MainActor @Sendable () -> Void)] = [
            (pasteTitle, "doc.on.clipboard", pasteTitle, nil, { paste(content) }),
        ]
        if trusted { // else Enter copies already
            rows.append((String(localized: "Copy Without Pasting"), "doc.on.doc", copyVerb, nil, { copy(content) }))
        }
        if let after = try? store.copied(after: id), !after.isEmpty {
            rows.append((String(localized: "Paste in Order from Here"), "list.number", pasteVerb, nil, {
                PasteQueue.shared.ids = after // the next ones wait in the empty launcher
                paste(content)
            }))
        }
        let pin = pinned ? String(localized: "Unpin", comment: "A clipboard item's action: no longer kept first")
            : String(localized: "Pin", comment: "A clipboard item's action: kept first, never cleared")
        rows.append((pin, pinned ? "pin.slash" : "pin", pin, nil, { try? store.pin(id, !pinned) }))
        switch content {
        case .text(let text):
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            if let url = URL(string: trimmed), ["http", "https"].contains(url.scheme?.lowercased() ?? ""), !trimmed.contains(" ") {
                rows.append((String(localized: "Open Link"), "safari", openVerb, nil, { NSWorkspace.shared.open(url) }))
            }
            rows.append((String(localized: "Large Type"), "textformat.size", showVerb, nil, { showLargeType(text) }))
            if let code = qrCode(trimmed) { rows.append((String(localized: "QR Code"), "qrcode", copyVerb, code, { copyPicture(code) })) }
        case .image(let png):
            let save: @MainActor @Sendable (URL) -> URL? = { folder in
                let stamp = Date.now.formatted(.iso8601.year().month().day().time(includingFractionalSeconds: false)).replacing(":", with: ".")
                let file = folder.appending(path: "Clipboard \(stamp).png")
                do { try png.write(to: file) } catch { notify(String(localized: "Couldn't save the picture"), error.localizedDescription); return nil }
                return file
            }
            rows.append((String(localized: "Open in Preview"), "eye", openVerb, nil, {
                if let file = save(FileManager.default.temporaryDirectory) { NSWorkspace.shared.open(file) }
            }))
            rows.append((String(localized: "Save to Downloads"), "square.and.arrow.down", saveVerb, nil, {
                if let file = save(.downloadsDirectory) { NSWorkspace.shared.activateFileViewerSelecting([file]) }
            }))
        }
        rows.append((String(localized: "Delete from History"), "trash", deleteVerb, nil, { try? store.delete(id) }))
        return rows.enumerated().map { index, row in
            var shown = image
            if let code = row.picture { shown = { roundedPicture(code) } } // the QR code beside the list
            return LauncherResult(id: "clipboard-action:\(row.title)", title: row.title, icon: .symbol(row.symbol), score: 50 - Double(index) / 100,
                                  actionTitle: row.actionTitle, action: row.action, preview: row.picture == nil ? preview : "",
                                  previewImage: shown, details: row.picture == nil ? details : [])
        }
    }

    private func action(_ mode: Mode, _ id: Int64) -> @MainActor @Sendable () -> Void {
        let (store, paste, copy) = (store, paste, copy)
        switch mode {
        case .paste: return { if let content = try? store.content(id) { paste(content) } }
        case .copy: return { if let content = try? store.content(id) { copy(content) } }
        case .delete: return { try? store.delete(id) }
        }
    }

    private func app(_ bundleID: String) -> (name: String, path: String)? {
        if let cached = apps[bundleID] { return cached }
        let found = NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundleID)
            .map { (FileManager.default.displayName(atPath: $0.path), $0.path) }
        apps[bundleID] = found
        return found
    }
}

/// Clipboard items waiting to be pasted one after another, in the order they were copied: the next one waits on top
/// of the empty launcher, so it's the hotkey and Enter each time (nothing watches ⌘V).
@MainActor final class PasteQueue {
    static let shared = PasteQueue()
    var ids: [Int64] = [] { didSet { touched = .now } }
    private(set) var touched = Date.now // started or pasted from; half an hour later it's forgotten, as a relaunch does
}

/// The empty launcher's row for the next item in `queue`: Enter pastes it, Tab stops. Items deleted since are skipped.
@MainActor func pasteNextRows(_ queue: PasteQueue, store: ClipboardStore, now: Date = .now,
                              paste: @escaping @MainActor @Sendable (ClipboardContent) -> Void) -> [LauncherResult] {
    if !queue.ids.isEmpty, now.timeIntervalSince(queue.touched) > 30 * 60 { queue.ids = [] }
    while let id = queue.ids.first, (try? store.content(id)) == nil { queue.ids.removeFirst() }
    guard let id = queue.ids.first, let content = try? store.content(id) else { return [] }
    let shown = switch content {
    case .text(let text): String(oneLine(text).prefix(80))
    case .image: String(localized: "a picture", comment: "Goes in “Paste Next: …”")
    }
    let left = queue.ids.count - 1
    return [LauncherResult(id: "paste-queue:\(id)", title: String(localized: "Paste Next: \(shown)"),
                           subtitle: left == 0 ? String(localized: "The last one")
                               : String(localized: "\(left) more after it, in the order you copied them"),
                           icon: .symbol("list.number"), score: 99.999, // under the meeting to join (100), over what's counting
                           actionTitle: String(localized: "Paste", comment: "Enter on the next clipboard item to paste in order"), action: {
        queue.ids.removeFirst()
        paste(content)
    }, actions: {
        [LauncherResult(id: "paste-queue:stop", title: String(localized: "Stop Pasting in Order"), icon: .symbol("stop"), score: 50,
                        actionTitle: String(localized: "Stop", comment: "Enter on Stop Pasting in Order"), action: { queue.ids = [] })]
    })]
}

/// Sends ⌘V to whichever app has focus once the panel is gone. Needs Accessibility.
@MainActor func sendPaste() { sendKeystroke(kVK_ANSI_V, .maskCommand) }

/// Pastes `text`, then puts back what was on the clipboard: a snippet shouldn't replace what you copied, or turn up
/// in the next one's `{clipboard}`. Both changes are marked transient, so clipboard history skips them.
@MainActor func pasteKeepingClipboard(_ text: String, pasteboard: NSPasteboard = .general,
                                      paste: @MainActor () -> Void = sendPaste, wait: Duration = .milliseconds(600)) async {
    let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    let saved = (pasteboard.pasteboardItems ?? []).map { item in
        let copy = NSPasteboardItem()
        for type in item.types { item.data(forType: type).map { _ = copy.setData($0, forType: type) } }
        return copy
    }
    let snippet = NSPasteboardItem()
    snippet.setString(text, forType: .string)
    snippet.setData(Data(), forType: transient)
    pasteboard.clearContents()
    pasteboard.writeObjects([snippet])
    let pasted = pasteboard.changeCount
    paste()
    // ponytail: a fixed wait for the app to take the paste; raise it if a slow app ever pastes the old clipboard.
    try? await Task.sleep(for: wait)
    guard pasteboard.changeCount == pasted else { return } // you copied something meanwhile: that stays
    pasteboard.clearContents()
    saved.first?.setData(Data(), forType: transient)
    pasteboard.writeObjects(saved)
}

/// Types a key with modifiers, as if on the keyboard (needs Accessibility), `times` times.
@MainActor func sendKeystroke(_ key: Int, _ flags: CGEventFlags, times: Int = 1, after wait: Duration = .milliseconds(100)) {
    Task {
        try? await Task.sleep(for: wait) // let focus get back to the previous app first
        let source = CGEventSource(stateID: .combinedSessionState)
        // ponytail: kVK_ANSI_* is the key's position on a US keyboard; Dvorak etc. would need a layout lookup.
        for _ in 0..<times { for keyDown in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(key), keyDown: keyDown)
            event?.flags = flags
            event?.post(tap: .cghidEventTap)
        } }
    }
}

/// Shows the system's "allow Accessibility" prompt and opens the matching System Settings pane.
@MainActor func requestAccessibility() {
    // The literal is kAXTrustedCheckOptionPrompt, which Swift 6 won't let us read (a global var).
    _ = AXIsProcessTrustedWithOptions(["AXTrustedCheckOptionPrompt": true] as CFDictionary)
    NSWorkspace.shared.open(URL(string: "x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility")!)
}
